// Writes content/download.md (git-ignored) from the latest published GitHub release, so /download
// links straight to its installers. Drafts and pre-releases are skipped, as auto-update skips them.
// The site rebuilds when a release is published (.github/workflows/sites.yml).
// GH_TOKEN or GITHUB_TOKEN, when set, raises GitHub's rate limit. In CI a failed request fails the
// build, so a deploy never replaces real links with "no release yet"; locally it only warns.
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { downloadUrl, findInstallers, formatSize, isBeta, readUnnotarized, readUnsigned } from '../../desktop/scripts/installers.mjs';

const repo = 'chriscasper/startica';
const here = path.dirname(fileURLToPath(import.meta.url));
const target = path.resolve(here, '../content/download.md');

async function latestRelease() {
  const token = process.env.GH_TOKEN || process.env.GITHUB_TOKEN;
  const response = await fetch(`https://api.github.com/repos/${repo}/releases/latest`, {
    headers: { accept: 'application/vnd.github+json', ...(token ? { authorization: `Bearer ${token}` } : {}) },
  });
  if (response.status === 404) return null; // nothing published yet
  if (!response.ok) throw new Error(`GitHub answered ${response.status} ${response.statusText}`);
  return response.json();
}

let release = null;
try {
  const latest = await latestRelease();
  if (latest) {
    const installers = findInstallers(latest.assets)
      .filter((i) => i.asset)
      .map(({ id, os, label, short, asset }) => ({
        id,
        os,
        label,
        short,
        name: asset.name,
        size: formatSize(asset.size),
        url: downloadUrl(repo, latest.tag_name, asset.name),
      }));
    release = {
      version: latest.tag_name.replace(/^v/, ''),
      beta: isBeta(latest.tag_name),
      date: new Date(latest.published_at).toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric', timeZone: 'UTC' }),
      url: latest.html_url,
      // Releases from before the notes recorded signing are treated as unsigned.
      unsigned: readUnsigned(latest.body) ?? ['macos', 'windows'],
      unnotarized: readUnnotarized(latest.body),
      // Grouped by system for the page's three cards: { macos: [...], windows: [...], linux: [...] }
      installers: Object.groupBy(installers, (i) => i.os),
    };
  }
} catch (error) {
  if (process.env.CI) {
    console.error(`Couldn't read the latest release: ${error.message}`);
    process.exit(1);
  }
  console.warn(`Couldn't read the latest release (${error.message}); /download will say there's no release yet.`);
}

// JSON is valid YAML, so the release goes into the front matter as one value.
await writeFile(
  target,
  `---
title: Download
layout: download
description: Download Startica for macOS, Windows or Linux. Free and open source; bring your own Claude or OpenAI key.
release: ${JSON.stringify(release)}
---

<!-- Generated by scripts/release.mjs from the latest GitHub release. The page is layouts/download.njk. -->
`,
);
console.log(release ? `Wrote content/download.md (${release.version})` : 'Wrote content/download.md (no release yet)');
